"""Assemble the cited-only prior-work comparison table for the APSIPA 2026
manuscript.

This script does not run any model. It collects numbers reported in prior
EEG-biometric papers under their own protocols and writes a LaTeX
``tabular`` body that the manuscript can ``\\input`` into a floating
table. Each row carries an explicit protocol footnote so the reader can
see that the comparison is not under a unified protocol.

The "This work (V4)" row is filled from Table~\\ref{tab:cross} of the
manuscript: best Precision@1 per noise family on the AEP dataset under
the held-out-subject open-set protocol used throughout the paper.

Output: ``docs/apsipa2026/tables/priorwork.tex``.

Usage::

    python -m experiments.analysis.build_priorwork_table

No GPU, no external data, no checkpoints required. Re-run any time the
``ROWS`` block below changes.
"""

from __future__ import annotations

from dataclasses import dataclass
from pathlib import Path


@dataclass(frozen=True)
class PriorWorkRow:
    """One row of the prior-work table.

    All fields are LaTeX-ready strings. ``score`` is whatever the source
    paper reports as its headline identification number under its own
    protocol; mixing accuracy / P@1 / EER is unavoidable when comparing
    cited results across papers, so the metric column is per-row rather
    than shared.
    """

    method: str
    cite_key: str
    dataset: str
    subjects: str
    metric: str
    score: str
    protocol_note: str


ROWS: tuple[PriorWorkRow, ...] = (
    PriorWorkRow(
        method="MindID",
        cite_key="zhang2017mindid",
        dataset="EEG-ID",
        subjects="8",
        metric="Acc.",
        score="0.984",
        protocol_note=(
            "Within-session resting-state EEG; attention-RNN; "
            "no synthetic noise injection."
        ),
    ),
    PriorWorkRow(
        method="EEG-Triplet",
        cite_key="yang2022eeg",
        dataset="PhysioNet MI",
        subjects="109",
        metric="Acc.",
        score="0.961",
        protocol_note=(
            "Motor-imagery task; triplet loss on raw signals; "
            "session-mixed split."
        ),
    ),
    PriorWorkRow(
        method="BrainNet",
        cite_key="fallahi2023brainnet",
        dataset="ERP-CORE",
        subjects="40",
        metric="EER",
        score="0.027",
        protocol_note=(
            "Siamese network on ERP epochs; cross-session evaluation; "
            "open-set verification on enrolled subjects only."
        ),
    ),
    PriorWorkRow(
        method="AISEI v0",
        cite_key="vu2026aisei",
        dataset="PhysioNet AEP",
        subjects="20",
        metric="P@1",
        score="0.860",
        protocol_note=(
            "Same dataset and same AEP-Hybrid protocol as this work; "
            "WaveNet-only denoiser; power-line noise."
        ),
    ),
)


def render_priorwork_table() -> str:
    """Return the full LaTeX table environment as a single string."""

    lines: list[str] = []
    lines.append(r"% Auto-generated by experiments/analysis/build_priorwork_table.py.")
    lines.append(r"% Re-run that script to regenerate; do not edit by hand.")
    lines.append(r"\begin{table}[t]")
    lines.append(r"\centering")
    lines.append(
        r"\caption{Cited prior-work numbers on EEG-based identification. "
        r"Each row uses its source paper's protocol; no baseline is "
        r"re-implemented under the AEP-Hybrid protocol of this paper. "
        r"V4 results are in Table~\ref{tab:cross}.}"
    )
    lines.append(r"\label{tab:priorwork}")
    lines.append(r"\begin{threeparttable}")
    lines.append(r"\scriptsize")
    lines.append(r"\setlength{\tabcolsep}{3pt}")
    lines.append(r"\begin{tabular}{l l c c c}")
    lines.append(r"\toprule")
    lines.append(
        r"\textbf{Method} & \textbf{Dataset} & \textbf{Subj.} "
        r"& \textbf{Metric} & \textbf{Score} \\"
    )
    lines.append(r"\midrule")

    for idx, row in enumerate(ROWS, start=1):
        lines.append(
            f"{row.method}~\\cite{{{row.cite_key}}}\\tnote{{{idx}}} & "
            f"{row.dataset} & {row.subjects} & {row.metric} & {row.score} \\\\"
        )

    lines.append(r"\bottomrule")
    lines.append(r"\end{tabular}")
    lines.append(r"\begin{tablenotes}\scriptsize")
    for idx, row in enumerate(ROWS, start=1):
        lines.append(f"\\item[{idx}] {row.protocol_note}")
    lines.append(r"\end{tablenotes}")
    lines.append(r"\end{threeparttable}")
    lines.append(r"\end{table}")
    return "\n".join(lines) + "\n"


def main() -> None:
    repo_root = Path(__file__).resolve().parents[2]
    out_path = repo_root / "docs" / "apsipa2026" / "tables" / "priorwork.tex"
    out_path.parent.mkdir(parents=True, exist_ok=True)
    body = render_priorwork_table()
    out_path.write_text(body, encoding="utf-8")
    print(f"wrote {out_path} ({len(body)} bytes, {len(ROWS)} prior rows)")


if __name__ == "__main__":
    main()
